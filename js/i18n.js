const _lang = 'en'; // English always — DE kept in LOCALES for optional future use
window.__lang = _lang;
window.__t = (key) => (LOCALES[_lang][key] ?? LOCALES['en'][key]) ?? key;

window.applyI18n = function() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key  = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    const val  = window.__t(key);
    if (attr) { el.setAttribute(attr, val); }
    else { el.textContent = val; }
  });
};

document.addEventListener('DOMContentLoaded', window.applyI18n);

